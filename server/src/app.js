const express = require('express');
const cors = require('cors');
const helmet = require('helmet');
const morgan = require('morgan');
const { notFound, errorHandler } = require('./middleware/error');
const app = express();
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_URL || 'http://localhost:5173' }));
app.use(express.json());
if (process.env.NODE_ENV !== 'test') app.use(morgan('dev'));
app.get('/api/health', (req, res) => res.json({ ok: true }));
const mount = (p, f) => app.use(p, require(f));
mount('/api/auth', './routes/auth.routes');
mount('/api/staff', './routes/staff.routes');
mount('/api/users', './routes/users.routes');
mount('/api/products', './routes/products.routes');
mount('/api/taxes', './routes/taxes.routes');
mount('/api/discounts', './routes/discounts.routes');
mount('/api/templates', './routes/templates.routes');
mount('/api/plans', './routes/plans.routes');
mount('/api/subscriptions', './routes/subscriptions.routes');
mount('/api/billing', './routes/billing.routes');
mount('/api/invoices', './routes/invoices.routes');
mount('/api', './routes/payments.routes'); // P4 defines '/payments' and '/invoices/:id/payments'
mount('/api/dashboard', './routes/dashboard.routes');
mount('/api/me', './routes/me.routes');
app.use(notFound);
app.use(errorHandler);
module.exports = app;
